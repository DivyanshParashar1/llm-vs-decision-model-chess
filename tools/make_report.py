"""Render reports/RESULTS_TABLES.md from notebook outputs (results.json + pilot/D* scaling/costs).

Usage: python tools/make_report.py build/chess-06-eval/out/results.json
Numbers only; the narrative write-up lives in reports/RESULTS.md and cites these tables.
"""
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
REP = ROOT / "reports"

ORDER = ["C1 LLM0", "C2 LLM0→D0", "C3 LLM*", "C4 LLM0→D*", "C5 LLM*→D*",
         "X1 D* all-legal", "X2 oracle(LLM0 cands)", "X3 random(LLM0 cands)"]


def pct(x):
    return "–" if x is None or x != x else f"{100 * x:.1f}"


def ci(s):
    if not isinstance(s, str):
        return ""
    lo, hi = [float(v) for v in s.strip("[]").split(",")]
    return f"[{100 * lo:.1f}, {100 * hi:.1f}]"


def main_table(split, r):
    t = r["table"]
    lines = [f"### {split} (n={r['n']})", "",
             "| Config | Legal % | Top-1 % [95% CI] | Top-3 % | Win-prob loss [95% CI] | Blunder % | Recall@5 % | Full-line puzzle solve % |",
             "|---|---|---|---|---|---|---|---|"]
    for name in ORDER:
        if name not in t:
            continue
        m = t[name]
        wpl_ci = m["wp_loss_ci"]
        lines.append(f"| {name} | {pct(m['legal'])} | {pct(m['top1'])} {ci(m['top1_ci'])} | {pct(m['top3'])} | "
                     f"{m['wp_loss']:.3f} {wpl_ci} | {pct(m['blunder'])} | {pct(m.get('recall@k'))} | "
                     f"{pct(r['full_line_puzzle_solve'].get(name))} |")
    lines += ["", "McNemar exact p-values (paired top-1):", ""]
    lines += [f"- {k}: p = {v:.4g}" for k, v in r["mcnemar"].items()]
    for col, s in r["slices"].items():
        # stored as {slice_value: {config: top1}} (pandas to_json default); flip to {config: {slice_value: top1}}
        if not any(k in ORDER for k in s):
            flipped = {}
            for val, d in s.items():
                for cfg_name, v in d.items():
                    flipped.setdefault(cfg_name, {})[val] = v
            s = flipped
        cols = sorted({c for d in s.values() for c in d})
        lines += ["", f"Top-1 % by {col}:", "", "| Config | " + " | ".join(cols) + " |",
                  "|---|" + "---|" * len(cols)]
        for name in ORDER:
            if name in s:
                lines.append(f"| {name} | " + " | ".join(pct(s[name].get(c)) for c in cols) + " |")
    return "\n".join(lines)


def main():
    res = json.load(open(sys.argv[1]))
    out = ["# Results tables (auto-generated by tools/make_report.py)", ""]
    for split in ["test", "test_ood"]:
        if split in res:
            out += [main_table(split, res[split]), ""]

    sc = json.load(open(REP / "dstar_val.json"))
    out += ["## D* data-scaling curve (val, 2,002 positions)", "",
            "| Model | Top-1 % | Picks gold candidate % | Win-prob loss | Blunder % |", "|---|---|---|---|---|"]
    for k, v in sc.items():
        out.append(f"| {k} | {pct(v.get('top1'))} | {pct(v.get('gold_acc'))} | "
                   f"{v['wp_loss']:.3f} | {pct(v.get('blunder'))} |" if "wp_loss" in v and "gold_acc" in v
                   else f"| {k} | {pct(v.get('top1'))} | – | {v.get('wp_loss', float('nan')):.3f} | – |")

    llm = json.load(open(REP / "cost_llm_star.json"))
    dst = json.load(open(REP / "cost_dstar.json"))["runs"]
    pilot = json.load(open(REP / "pilot_report.json"))
    gen_h = pilot["gen_minutes"] / 60
    out += ["", "## Training cost (Kaggle, Tesla T4)", "",
            "| Arm | Trainable params | Train positions | GPU-hours (training) | Peak VRAM GB |", "|---|---|---|---|---|",
            f"| LLM* (QLoRA r16, Qwen3-8B) | {llm['trainable_params'] / 1e6:.1f}M | {llm['n_train_positions']:,} | "
            f"{llm['gpu_hours']:.2f} | {llm['peak_vram_gb']:.1f} |"]
    for r in sorted(dst, key=lambda r: r["n_train_positions"]):
        out.append(f"| D* (full FT, GLiNER2.5-Decide) | {r['trainable_params'] / 1e6:.0f}M | {r['n_train_positions']:,} | "
                   f"{r['gpu_hours']:.2f} | {r['peak_vram_gb']:.1f} |")
    out += ["", f"LLM₀ candidate generation for all 24,408 positions took {gen_h:.2f} h on 2×T4 "
                f"(one Kaggle session); the train share (~{19894 / 24408:.0%}) is a real cost of the C4 approach."]
    (REP / "RESULTS_TABLES.md").write_text("\n".join(out) + "\n")
    print(REP / "RESULTS_TABLES.md")


if __name__ == "__main__":
    main()
